/// Pull the pending exception out of the realm and render it readably.
fn format_exception(ctx: &Ctx<'_>) -> String {
    let exc = ctx.catch();
    let obj = exc.as_object();
    let name = obj
        .and_then(|o| o.get::<_, String>("name").ok())
        .unwrap_or_else(|| "Error".into());
    let message = obj
        .and_then(|o| o.get::<_, String>("message").ok())
        .unwrap_or_else(|| format!("{exc:?}"));
    let mut s = format!("{name}: {message}");
    if let Some(stack) = obj.and_then(|o| o.get::<_, String>("stack").ok()) {
        s.push('\n');
        s.push_str(&stack);
    }
    s
}
