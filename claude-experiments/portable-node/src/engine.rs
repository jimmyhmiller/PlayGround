// internalBinding dispatch
// -------------------------------------------------------------------------

/// `internalBinding(name)` from Node's sources lands here.
///
/// A short list is implemented natively, because it is the hot byte path or
/// needs engine introspection. Everything else resolves to the portable JS
/// module `__binding/<name>`, which calls `__host.*`. Missing both is an
/// error naming the binding, which is how the next gap announces itself.
fn dispatch_internal_binding<'js>(ctx: Ctx<'js>, name: String) -> Result<Object<'js>> {
    match name.as_str() {
        "buffer" => return crate::buffer_binding::make(ctx),
        "util" => return crate::util_binding::make(ctx),
        "config" => return crate::util_binding::make_config(ctx),
        _ => {}
    }

    let require: Function<'js> = ctx.globals().get("require")?;
    let module_name = format!("__binding/{name}");
    match require.call::<_, Object<'js>>((module_name.as_str(),)) {
        Ok(o) => Ok(o),
        Err(_) => {
            let msg = format!(
                "portable-node: internalBinding({name:?}) not implemented \
                 (no Rust impl and no JS shim '__binding/{name}')"
            );
            let err = rquickjs::Exception::from_message(ctx.clone(), &msg)?;
            Err(ctx.throw(err.into_value()))
        }
    }
}

