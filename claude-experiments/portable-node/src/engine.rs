//! The QuickJS integration layer: everything between the engine's embedding
//! API and the portable JS in `js/bootstrap.js`.
//!
//! Nothing here knows about HTTP, sockets, files, or Node. It knows how to
//! stand up a realm, hand JS the two globals it needs to reach native code
//! (`__host` and `__internalBinding`), and drive the loop. Porting to a
//! different engine means rewriting this file and nothing else on the Rust
//! side; porting to a different language means reimplementing this file plus
//! the `__host` primitives it installs.
//!
//! The integration surface is deliberately tiny:
//!
//!   * set a global                     -> `ctx.globals().set(..)`
//!   * evaluate a string                -> `ctx.eval(..)`
//!   * expose a native function         -> `Func::from(rust_fn)`
//!   * run one queued microtask         -> `rt.execute_pending_job()`
//!   * throw / catch a JS exception     -> `ctx.throw(..)` / `ctx.catch()`
//!
//! Async work never crosses the boundary as a callback. Host ops return
//! integer op_ids; JS owns the callback table; completions come back only
//! through `__ioDrain`, on this thread, inside the loop below.

use rquickjs::function::Func;
use rquickjs::{Context, Ctx, Function, Object, Result, Runtime};

/// A QuickJS runtime plus its realm, bootstrapped into a Node-shaped world.
pub struct Engine {
    rt: Runtime,
    context: Context,
}

impl Engine {
    /// Build a realm and bring up the JS layer:
    ///
    ///   1. `__internalBinding` so `internalBinding(name)` can find native code
    ///   2. `__host.*`, the portable primitive surface
    ///   3. `__nodeSourceFiles`, the name -> source table `require` reads
    ///   4. `bootstrap.js`, which builds primordials, the shims, the CJS
    ///      resolver, the timer queue, and the loop hooks this file calls
    pub fn new(sources: &[(&str, &str)]) -> std::result::Result<Engine, String> {
        let rt = Runtime::new().map_err(|e| e.to_string())?;
        let context = Context::full(&rt).map_err(|e| e.to_string())?;
        let engine = Engine { rt, context };

        engine.with(|ctx| -> Result<()> {
            ctx.globals()
                .set("__internalBinding", Func::from(dispatch_internal_binding))?;

            crate::host::install(ctx.clone())?;

            let registry: Object<'_> = ctx.eval("({})")?;
            for (name, src) in sources {
                registry.set(*name, *src)?;
            }
            ctx.globals().set("__nodeSourceFiles", registry)?;

            ctx.eval::<(), _>(include_str!("../js/bootstrap.js"))?;
            Ok(())
        })?;

        Ok(engine)
    }

    // ---- reaching into the realm -----------------------------------------

    /// Enter the realm and run `f`. A JS exception comes back as a formatted
    /// string (name, message, stack) rather than the opaque "Exception
    /// generated by QuickJS" rquickjs hands out by default.
    ///
    /// The borrow is held for exactly the closure's duration. Do NOT drive the
    /// loop from inside one: `pump` re-enters, and QuickJS's RefCell will
    /// panic with "already borrowed".
    pub fn with<F, T>(&self, f: F) -> std::result::Result<T, String>
    where
        F: FnOnce(&Ctx<'_>) -> Result<T>,
    {
        self.context.with(|ctx| match f(&ctx) {
            Ok(v) => Ok(v),
            Err(rquickjs::Error::Exception) => Err(format_exception(&ctx)),
            Err(other) => Err(format!("{other}")),
        })
    }

    /// Evaluate an expression and convert the result. Errors are formatted the
    /// same way `with` formats them.
    pub fn eval<T>(&self, code: &str) -> std::result::Result<T, String>
    where
        T: for<'js> rquickjs::FromJs<'js>,
    {
        self.with(|ctx| ctx.eval::<T, _>(code))
    }

    /// Evaluate for a value we can live without (a probe, a port number that
    /// may not exist yet). Any failure yields `default`.
    pub fn eval_or<T>(&self, code: &str, default: T) -> T
    where
        T: for<'js> rquickjs::FromJs<'js>,
    {
        self.with(|ctx| ctx.eval::<T, _>(code)).unwrap_or(default)
    }

    /// Set a global to a value convertible into JS.
    pub fn set_global<V>(&self, name: &str, value: V) -> std::result::Result<(), String>
    where
        V: for<'js> rquickjs::IntoJs<'js>,
    {
        self.with(|ctx| ctx.globals().set(name, value))
    }

    /// `require(path)` from the top level, the way the script runner starts a
    /// user program.
    pub fn require(&self, path: &str) -> std::result::Result<(), String> {
        self.set_global("__userScriptPath", path)?;
        self.eval::<()>("require(__userScriptPath)")
    }

    // ---- the loop ---------------------------------------------------------

    /// Drain the engine's job queue: promise reactions and, since
    /// `process.nextTick` is a microtask here, ticks too.
    ///
    /// Must run outside `with`: the runtime is locked by the realm guard.
    pub fn drain_microtasks(&self) {
        loop {
            match self.rt.execute_pending_job() {
                Ok(true) => continue, // ran one; keep going
                Ok(false) => break,   // queue empty
                Err(_) => break,      // job threw; the next eval surfaces it
            }
        }
    }

    /// Run until nothing is pending, or until `max_ms` of wall clock elapses.
    ///
    /// One turn is: drain microtasks, ask JS what is outstanding, block once in
    /// `__ioDrain` (which is the only blocking call in the whole system), then
    /// fire due timers. A listening server always has work, so `None` here
    /// means "serve forever".
    pub fn pump(&self, max_ms: Option<u64>) -> std::result::Result<(), String> {
        let deadline =
            max_ms.map(|m| std::time::Instant::now() + std::time::Duration::from_millis(m));

        loop {
            if let Some(d) = deadline {
                if std::time::Instant::now() >= d {
                    break;
                }
            }

            self.drain_microtasks();

            // What is outstanding, and how long may we sleep? Timers give a
            // deadline; pending I/O with no timer means "wait for the network".
            let (has_work, sleep_ms): (bool, f64) = self.context.with(|ctx| {
                let has_timers: bool = ctx.eval("__eventLoopHasWork()").unwrap_or(false);
                let has_io: bool = ctx.eval("__ioHasPending()").unwrap_or(false);
                if !has_timers && !has_io {
                    return (false, 0.0);
                }
                let timeout_ms = if has_timers {
                    let due: f64 = ctx.eval("__eventLoopNextDueMs()").unwrap_or(f64::INFINITY);
                    let now: f64 = ctx.eval("__host.time.now_ms()").unwrap_or(0.0);
                    (due - now).max(0.0).min(60_000.0)
                } else {
                    60_000.0
                };
                (true, timeout_ms)
            });
            if !has_work {
                break;
            }

            // Never sleep past our own deadline.
            let sleep_ms = match deadline {
                Some(d) => {
                    let remaining =
                        d.saturating_duration_since(std::time::Instant::now()).as_millis() as f64;
                    sleep_ms.min(remaining).max(0.0)
                }
                None => sleep_ms,
            };

            // Block in the host's poll, then dispatch completions to their JS
            // callbacks. Errors inside a callback are reported by __ioDrain
            // itself (with a stack); a throw out of the drain is not fatal.
            self.context.with(|ctx| {
                let _ = ctx.eval::<u32, _>(format!("__ioDrain({sleep_ms})").as_str());
            });

            self.context.with(|ctx| {
                let _ = ctx.eval::<(), _>("__eventLoopFireDue()");
            });
        }
        Ok(())
    }

    /// Pump until idle. For a program holding a listening socket, forever.
    pub fn run_until_idle(&self) -> std::result::Result<(), String> {
        self.pump(None)
    }

    /// Pump for at most `ms`, then return whatever state we are in. Used by the
    /// self-test to interleave JS progress with an external client.
    pub fn run_for(&self, ms: u64) -> std::result::Result<(), String> {
        self.pump(Some(ms))
    }
}

