//! Diagnostics produced by the default resolver's runtime policy.

use std::path::Path;

use crate::resolver_policy::{bare_package_name, host_provided_scheme};

pub fn node_builtin_in_browser_message(path: &Path, specifier: &str) -> String {
    format!(
        "Node built-in {specifier:?} cannot be bundled for the browser: browsers have no such module\n  imported by {}\n  a browser build has no Node runtime to resolve it, so this import cannot work at runtime\n  diffpack does NOT implement webpack/Next-style browser polyfills for Node built-ins; that is an unimplemented feature, not a resolution failure\n  either keep this module out of the client graph (import it only from server code), or replace it with a browser-safe equivalent",
        path.display()
    )
}

pub fn host_provided_module_message(path: &Path, specifier: &str) -> String {
    let scheme = host_provided_scheme(specifier).unwrap_or_default();
    format!(
        "{specifier:?} names a module the {scheme:?} runtime provides, so it was left external rather than bundled\n  imported by {}\n  a `scheme:` specifier is a host-defined import (like `node:fs`): nothing on disk can satisfy it and no package manager can install it\n  running on that host, the host resolves it; running anywhere else, the import throws exactly where it would without a bundler",
        path.display()
    )
}

pub fn specifier_resolves_two_ways_message(
    path: &Path,
    specifier: &str,
    as_import: &Path,
    as_require: &Path,
) -> String {
    format!(
        "{} reaches {specifier:?} through both a CommonJS `require(...)` and an ESM `import`, and the two resolve to different files\n  `import {specifier:?}`  -> {}\n  `require({specifier:?})` -> {}\n  that package's `exports` map sends the two conditions to different builds, so Node itself loads two separate module instances here\n  the bundle records one target per specifier per module, so it cannot carry both, and picking either one would give the other call site the wrong module\n  use ONE syntax for this specifier in this file (or import the exact subpath each call site wants)",
        path.display(),
        as_import.display(),
        as_require.display()
    )
}

pub fn optional_dependency_missing_message(path: &Path, specifier: &str) -> String {
    let mut message = format!(
        "optional dependency {specifier:?} is not installed, so it was not bundled\n  required by {}\n  every reference to it is a `require(...)` inside a `try` block, so this module already handles it being absent\n  the emitted require throws at exactly the point Node's would, and that module's `catch` runs",
        path.display()
    );
    if let Some(package) = bare_package_name(specifier) {
        message.push_str(&format!("\n  install it to use it:  npm install {package}"));
    }
    message
}

/// Render an unresolved import with package/path remediation. Integrations may
/// provide a more accurate explanation for a package the tool itself requires.
pub fn unresolved_import_message(
    path: &Path,
    specifier: &str,
    error: &str,
    generated: bool,
    package_help: Option<&str>,
) -> String {
    let file_name = path.file_name().and_then(|name| name.to_str());
    let mut message = format!("cannot resolve {specifier:?}: {error}");
    if file_name == Some("__diffpack_virtual_module__.js") {
        message.push_str("\n  imported by a diffpack build-generated virtual module");
    } else {
        message.push_str(&format!("\n  imported by {}", path.display()));
        if generated {
            message.push_str("\n              (generated by diffpack, not by your app)");
        }
    }
    match bare_package_name(specifier) {
        Some(_) if package_help.is_some() => {
            message.push_str(package_help.expect("checked above"));
        }
        Some(package) => message.push_str(&format!("\n  install it:  npm install {package}")),
        None if specifier.starts_with('#') => message.push_str(
            "\n  a `#` specifier resolves through the nearest package.json `imports` field; check that it maps this specifier",
        ),
        None => message
            .push_str("\n  no file matched that path; check the spelling and the file extension"),
    }
    message
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn optional_package_diagnostic_includes_install_hint() {
        let message = optional_dependency_missing_message(Path::new("src/app.js"), "@x/y/sub");
        assert!(message.contains("npm install @x/y"));
        assert!(message.contains("src/app.js"));
    }

    #[test]
    fn unresolved_import_distinguishes_packages_paths_and_generated_importers() {
        let package = unresolved_import_message(
            Path::new(".generated/entry.js"),
            "@scope/pkg/sub",
            "missing",
            true,
            None,
        );
        assert!(package.contains("npm install @scope/pkg"));
        assert!(package.contains("generated by diffpack"));
        let path = unresolved_import_message(
            Path::new("src/app.js"),
            "./missing.js",
            "missing",
            false,
            None,
        );
        assert!(path.contains("check the spelling"));
    }
}
